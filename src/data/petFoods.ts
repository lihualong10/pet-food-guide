export const pets: Pet[] = PET_META.map((meta) => ({
  ...meta,
  foods: MASTER_FOODS
    .filter((f) => f.ratings[meta.slug])
    .map((f) => {
      const r = f.ratings[meta.slug];
      return {
        name: f.name,
        nameEn: f.nameEn,
        aliases: f.aliases,
        emoji: getFoodEmoji(f.name, f.category),
        safety: r.safety,
        reason: r.reason,
        note: r.note,
      };
    }),
}));

/** 根据 slug 获取宠物数据 */
export function getPetBySlug(slug: string): Pet | undefined {
  return pets.find((pet) => pet.slug === slug.toLowerCase());
}

